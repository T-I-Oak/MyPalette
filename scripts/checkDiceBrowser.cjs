const { chromium } = require(process.env.MYPALETTE_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.argv[2] || 'http://127.0.0.1:3000/MyPalette/dev.html';
(async () => {
    const browser = await chromium.launch({ channel: process.env.MYPALETTE_BROWSER_CHANNEL || 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.status() >= 400) requests.push(response.url()); });
    await page.goto(base + '#dice');
    const roll = page.getByRole('button', { name: '使う画材を決める', exact: true });
    await roll.waitFor();
    assert.equal(await page.locator('#app-version').textContent(), require('../package.json').version);
    assert.equal(await page.locator('.DiceResult:not([hidden])').count(), 0);
    async function completeRoll() {
        await roll.click();
        await page.waitForFunction(() => !document.querySelector('.texture-primary').disabled, null, { timeout: 60000 });
        assert.doesNotMatch(await page.locator('.DiceMessage').textContent(), /停止できません|操作できません/);
    }
    await completeRoll();
    assert.equal(await page.locator('.DiceResult:not([hidden])').count(), 3);
    await page.waitForTimeout(1000);
    await page.screenshot({ path: 'tmp_dice_desktop.png' });
    const third = await page.locator('.DiceReadout').nth(2).textContent();
    await page.getByLabel('ロール対象', { exact: true }).selectOption('selected');
    await page.locator('.DiceSelection input').nth(2).uncheck();
    await roll.click();
    await page.waitForFunction(() => document.querySelectorAll('.DiceResult:not([hidden])').length === 1);
    await page.waitForFunction(() => !document.querySelector('.texture-primary').disabled, null, { timeout: 60000 });
    assert.equal(await page.locator('.DiceReadout').nth(2).textContent(), third);
    await page.getByLabel('ロール対象', { exact: true }).selectOption('single');
    await completeRoll();
    const index = Number((await page.locator('.DiceReadout').first().textContent()).match(/index (\d)/)[1]);
    await page.locator('.DiceFaceEditor').nth(index).getByLabel('面の種類').selectOption('fame1');
    assert.match(await page.locator('.DiceReadout').first().textContent(), /名声/);
    await page.waitForFunction(() => document.querySelector('.DiceResult img').alt.includes('名声'));
    await page.getByRole('button', { name: '消費済みにする', exact: true }).click();
    await roll.click();
    await page.waitForFunction(() => document.querySelector('.DiceMessage').textContent.includes('consumed'));
    await page.getByRole('button', { name: '未消費に戻す', exact: true }).click();
    await page.getByLabel('追加する面構成').selectOption('temporaryYellowPurple1');
    await page.getByRole('button', { name: 'ダイスを追加', exact: true }).click();
    await completeRoll();
    assert.match(await page.locator('.DiceMessage').textContent(), /黄・紫/);
    await page.waitForTimeout(800);
    await page.screenshot({ path: 'tmp_dice_special.png' });
    await page.getByLabel('ロール対象', { exact: true }).selectOption('all');
    await roll.click();
    await page.getByRole('button', { name: 'このダイスを削除', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.texture-primary').disabled, null, { timeout: 60000 });
    assert.match(await page.locator('.DiceMessage').textContent(), /削除による中止/);
    assert.equal(await page.locator('.DiceRow').count(), 3);
    await page.getByRole('button', { name: '対象を空中回転へ戻す', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.DiceResult:not([hidden])').length === 0);
    await completeRoll();
    const sizes = [[1280, 720], [768, 1024], [390, 844], [844, 390]];
    const dimensions = [];
    for (const [width, height] of sizes) {
        await page.setViewportSize({ width, height });
        await page.waitForTimeout(500);
        const layout = await page.evaluate(() => {
            const rect = selector => { const r = document.querySelector(selector).getBoundingClientRect(); return { x:r.x, y:r.y, w:r.width, h:r.height, bottom:r.bottom, right:r.right }; };
            return { viewport: rect('.DiceViewport'), controls: rect('.DiceControls'), root: rect('.Screen'),
                overflow: document.documentElement.scrollWidth > innerWidth || document.documentElement.scrollHeight > innerHeight };
        });
        assert.equal(layout.overflow, false);
        assert.ok(layout.controls.bottom <= height + 1, JSON.stringify(layout));
        assert.ok(layout.viewport.h >= 150, JSON.stringify(layout));
        dimensions.push({ width, height, ...layout });
        await page.screenshot({ path: `tmp_dice_${width}.png` });
    }
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.locator('.DiceGallery summary').click();
    assert.equal(await page.locator('.DiceSample').count(), 46);
    await page.screenshot({ path: 'tmp_dice_gallery.png' });
    await page.locator('.DiceGallery').evaluate(node => node.scrollTop = node.scrollHeight);
    await page.screenshot({ path: 'tmp_dice_gallery_special.png' });
    await page.getByRole('button', { name: '入口へ戻る', exact: true }).click();
    await page.getByRole('button', { name: 'ダイス動作確認を開く', exact: true }).waitFor();
    assert.equal(await page.locator('.DiceViewport').count(), 0);
    assert.deepEqual(errors, []); assert.deepEqual(requests, []);
    await page.route('**/assets/dice/brush_grayscale.png', route => route.abort());
    await page.goto(base + '#dice'); await page.reload();
    await page.getByText(/画材画像を読み込めません/).waitFor();
    const result = { base, errors, requests, dimensions, checks: ['version', 'roll', 'old-result-hidden', 'selected-preserved', 'single', 'face-edit', 'consumed', 'special-result', 'remove-during-roll', 'prepare', 'repeat', 'resize', '46-icons', 'exit', 'asset-failure'] };
    fs.writeFileSync('tmp_dice_browser_results.json', JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result, null, 2));
    await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
