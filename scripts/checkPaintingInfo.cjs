const { chromium } = require(process.env.MYPALETTE_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');

(async () => {
    const browser = await chromium.launch({ channel: process.env.MYPALETTE_BROWSER_CHANNEL || 'msedge', headless: true });
    try {
        const page = await browser.newPage({ viewport: { width: 1200, height: 1000 }, deviceScaleFactor: 1.5 });
        const errors = [];
        page.on('pageerror', error => errors.push(error.message));
        await page.goto((process.argv[2] || 'http://127.0.0.1:3002/MyPalette/') + 'dev.html#easel');
        const compact = page.locator('.PaintingInfo .PaintingCard');
        await compact.waitFor();
        assert.equal(await compact.locator('.PaintingArtwork').isVisible(), false);
        assert.equal(await page.locator('.PaintingInfo button').filter({ hasText: /^達成$/ }).isVisible(), false);
        await compact.locator('.PaintingTitle').click();
        const detail = page.locator('.GameCardDetail');
        await detail.waitFor();
        assert.equal(await detail.locator('.PaintingArtwork').isVisible(), true);
        await detail.getByRole('tab', { name: 'Step 2', exact: true }).click();
        await detail.getByRole('button', { name: '閉じる', exact: true }).click();
        await page.waitForFunction(() => !document.querySelector('.GameCardDetail'));
        assert.equal(await page.getByLabel('ステップ', { exact: true }).inputValue(), '0');
        assert.equal(await compact.getByRole('tab', { name: 'Step 2', exact: true }).getAttribute('aria-selected'), 'true');
        const beforePossible = await compact.boundingBox();
        await page.getByLabel('達成可能（表示確認）', { exact: true }).check();
        assert.deepEqual(await compact.boundingBox(), beforePossible);
        assert.equal(await compact.evaluate(node => node.classList.contains('state-achievable')), true);
        await page.locator('.PaintingInfo').getByRole('button', { name: '達成', exact: true }).click();
        await page.waitForFunction(() => document.querySelector('.EaselViewport').dataset.step === '1');
        await page.getByLabel('ステップ', { exact: true }).selectOption('3');
        await page.waitForFunction(() => document.querySelector('.EaselViewport').dataset.step === '3');
        assert.equal(await page.locator('.PaintingInfo button').filter({ hasText: /^達成$/ }).isVisible(), false);
        await page.getByLabel('ステップ', { exact: true }).selectOption('1');
        await page.waitForFunction(() => document.querySelector('.EaselViewport').dataset.step === '1');
        const rect = await page.locator('.EaselViewport').boundingBox();
        await page.mouse.click(rect.x + rect.width / 2, rect.y + rect.height * .55);
        await detail.waitFor();
        assert.equal(await detail.locator('.PaintingArtwork').isVisible(), true);
        await detail.getByRole('button', { name: '閉じる', exact: true }).click();
        await page.screenshot({ path: 'tmp_painting_info.png' });
        await page.setViewportSize({ width: 390, height: 844 });
        await page.waitForTimeout(100);
        const bounds = await page.locator('.PaintingInfo').boundingBox();
        const viewportBounds = await page.locator('.EaselViewport').boundingBox();
        assert.ok(bounds.y >= viewportBounds.y);
        const beforeHidden = await compact.boundingBox();
        await page.getByLabel('達成可能（表示確認）', { exact: true }).uncheck();
        assert.deepEqual(await compact.boundingBox(), beforeHidden);
        await page.getByLabel('達成可能（表示確認）', { exact: true }).check();
        assert.deepEqual(await compact.boundingBox(), beforeHidden);
        await page.screenshot({ path: 'tmp_painting_info_mobile.png' });
        assert.deepEqual(errors, []);
        console.log('Painting info: compact/detail, step inspection, achievable state, preview achievement, canvas tap and mobile rendering passed.');
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
